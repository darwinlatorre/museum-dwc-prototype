import { TestBed } from '@angular/core/testing';
import { describe, expect, it, vi } from 'vitest';
import { NormalizationPreview } from './normalization-preview';
import { NormalizationPreviewState } from '../../pages/import-workbench/normalization-preview-state';
import { buildNormalizationPreview, readPreviewPage } from '../../engine/normalization-preview';
import type { PreviewRequest, PreviewResponse, PreviewWindow } from '../../models/normalization-preview';

const options = { trim: true, emptyMarkers: true, dates: true, coordinates: true, numbers: true, duplicates: true };
async function setup(extraColumns = 0) {
  const messages: PreviewRequest[] = [];
  const worker = { postMessage: vi.fn((message: PreviewRequest) => messages.push(structuredClone(message))), terminate: vi.fn(), onmessage: undefined as ((event: MessageEvent) => void) | undefined };
  let id = 0;
  const state = new NormalizationPreviewState(() => worker as unknown as Worker, () => ++id);
  const original = { headers: ['alias', 'empty', ...Array.from({ length: extraColumns }, (_, i) => `field${i}`)],
    rows: Array.from({ length: 15 }, (_, i) => ({ row: i + 2, values: [` ${i % 2 ? 'b' : 'a'} `, '', ...Array<string>(extraColumns).fill('')] })) };
  const snapshot = buildNormalizationPreview(original, {}, options);
  const reply = (request: PreviewRequest, override?: PreviewWindow) => {
    if (!('window' in request)) throw new Error('Falta ventana');
    const page = readPreviewPage(snapshot, override ?? request.window);
    const token = { id: request.id, session: request.session, generation: request.generation };
    const data: PreviewResponse = request.kind === 'preview-page'
      ? { ...token, kind: 'preview-page', ...page }
      : { ...token, kind: 'preview-ready', metadata: snapshot.metadata, ...page };
    worker.onmessage?.({ data } as MessageEvent);
  };
  state.reset(original, {});
  state.start(options);
  reply(messages[0]);
  if (state.paging()) reply(messages.at(-1)!);
  const fixture = TestBed.createComponent(NormalizationPreview);
  fixture.componentRef.setInput('state', state);
  fixture.componentRef.setInput('options', options);
  await fixture.whenStable();
  const root = fixture.nativeElement as HTMLElement;
  const header = (label: string) => root.querySelector<HTMLButtonElement>(`thead button[aria-label^="Ordenar por ${label}"]`)!;
  return { state, worker, messages, reply, fixture, root, header };
}
describe('cabeceras de Normalizar y ventana confirmada', () => {
  it('resizes a source column without asking the worker or modifying preview values', async () => {
    const p = await setup();
    const before = structuredClone(p.state.rows());
    const count = p.messages.length;
    const handle = p.root.querySelector<HTMLElement>('[role="slider"][aria-label="Ancho de alias"]');
    expect(handle).not.toBeNull();
    handle!.dispatchEvent(new KeyboardEvent('keydown', { key: 'ArrowRight', bubbles: true }));
    await p.fixture.whenStable();
    const width = handle!.getAttribute('aria-valuenow');
    expect(p.root.querySelectorAll('colgroup col')[1].getAttribute('style')).toContain(`${width}px`);
    expect(p.messages).toHaveLength(count);
    expect(p.state.rows()).toEqual(before);
    expect(p.header('Fila de origen').closest('th')?.getAttribute('aria-sort')).toBe('ascending');
    p.state.destroy();
  });
  it('separates preview formats and table presentation without recalculating on disclosure', async () => {
    const p = await setup();
    const count = p.messages.length;
    const settings = p.root.querySelector<HTMLDetailsElement>('.normalization-settings')!;
    expect(settings.open).toBe(false);
    settings.querySelector('summary')!.click();
    await p.fixture.whenStable();
    expect(p.messages).toHaveLength(count);
    expect(p.root.querySelector('[role="group"][aria-label="Presentación de la hoja"]')).not.toBeNull();
    expect(p.root.querySelector('nav[aria-label="Páginas de registros"] [role="group"]')).not.toBeNull();
    expect(settings.querySelectorAll('.normalization-rules li')).toHaveLength(6);
    expect(settings.querySelectorAll('input')).toHaveLength(0);
    p.state.destroy();
  });
  it('column navigation labels remain tied to the confirmed window during loading', async () => {
    const p = await setup(59);
    p.state.setHideEmpty(false); p.reply(p.messages.at(-1)!); await p.fixture.whenStable();
    const nav = () => p.root.querySelector('nav[aria-label="Ventana de columnas"]')!;
    expect(nav().textContent).toContain('Columnas fuente 1–50 de 61');
    const count = p.messages.length;
    [...nav().querySelectorAll('button')].find(button => button.textContent === 'Columnas siguientes')!.click();
    await p.fixture.whenStable();
    expect(nav().textContent).toContain('Columnas fuente 1–50 de 61');
    expect(p.messages).toHaveLength(count + 1);
    const request = p.messages.at(-1)!;
    expect(Object.keys(request).sort()).toEqual(['generation', 'id', 'kind', 'session', 'window']);
    p.reply(request); await p.fixture.whenStable();
    expect(nav().textContent).toContain('Columnas fuente 51–61 de 61');
    expect(p.root.querySelectorAll('thead th')).toHaveLength(12);
    p.state.destroy();
  });
  it('ordena por cabecera sin reenviar originales, opciones, aplicar ni nueva generación; cierra detalle', async () => {
    const p = await setup();
    expect(p.root.querySelector('table')?.classList.contains('museum-data-table')).toBe(true);
    expect(p.header('Fila de origen')?.closest('th')?.getAttribute('aria-sort')).toBe('ascending');
    p.state.page({ offset: 10 });
    p.reply(p.messages.at(-1)!);
    await p.fixture.whenStable();
    p.root.querySelector<HTMLButtonElement>('button[data-cell]')!.click();
    await p.fixture.whenStable();
    expect(p.root.querySelector('.normalization-original')).not.toBeNull();
    const count = p.messages.length;
    p.header('alias').focus();
    p.header('alias').click();
    await p.fixture.whenStable();
    const sortRequest = p.messages.at(-1)!;
    expect(sortRequest).toMatchObject({ kind: 'preview-page', generation: 1, window: { offset: 0, sort: { columnIndex: 0, direction: 'asc' } } });
    expect(Object.keys(sortRequest).sort()).toEqual(['generation', 'id', 'kind', 'session', 'window']);
    expect(p.messages).toHaveLength(count + 1);
    expect(p.root.querySelector('.normalization-original')).toBeNull();
    expect(p.root.querySelector('[aria-busy="true"]')).not.toBeNull();
    expect(p.header('Fila de origen').closest('th')?.getAttribute('aria-sort')).toBe('ascending');
    expect(p.header('alias').closest('th')?.getAttribute('aria-sort')).toBe('none');
    expect(document.activeElement).toBe(p.header('alias'));
    p.reply(sortRequest);
    await p.fixture.whenStable();
    expect(p.header('alias').closest('th')?.getAttribute('aria-sort')).toBe('ascending');
    const firstRow = p.root.querySelector('tbody th')!;
    expect(firstRow.firstChild?.textContent?.trim()).toBe('2');
    expect(Array.from(firstRow.querySelectorAll('small'), badge => badge.textContent)).toEqual(['Fila igual · row:1']);
    p.root.querySelector<HTMLButtonElement>('button[data-cell="2:0"]')!.click();
    await p.fixture.whenStable();
    expect(p.root.querySelector('.normalization-original')?.textContent).toContain('fila 2 · columna 1');
    expect(p.root.querySelector('.normalization-original dd')?.textContent).toBe(' a ');
    p.state.destroy();
  });
  it('descarta respuestas de sort anterior, confirma columnas/filas juntas y conserva controles de vista', async () => {
    const p = await setup();
    p.header('alias').click();
    await p.fixture.whenStable();
    const a = p.messages.at(-1)!;
    p.header('alias').click();
    await p.fixture.whenStable();
    const b = p.messages.at(-1)!;
    expect(b).toMatchObject({ window: { sort: { columnIndex: 0, direction: 'desc' } } });
    p.reply(a);
    expect(p.state.paging()).toBe(true);
    p.reply(b);
    await p.fixture.whenStable();
    expect(p.header('alias').closest('th')?.getAttribute('aria-sort')).toBe('descending');
    const firstRow = p.root.querySelector('tbody th')!;
    expect(firstRow.firstChild?.textContent?.trim()).toBe('3');
    expect(Array.from(firstRow.querySelectorAll('small'), badge => badge.textContent)).toEqual(['Fila igual · row:2']);
    p.reply(a);
    expect(p.state.rows()[0].sourceRow).toBe(3);
    const generation = b.generation;
    p.state.setHideEmpty(false);
    const columns = p.messages.at(-1)!;
    expect(p.state.columns()).toHaveLength(1);
    p.reply(columns);
    await p.fixture.whenStable();
    expect(p.header('empty')).not.toBeNull();
    expect(p.state.columns()).toHaveLength(2);
    p.root.querySelector<HTMLButtonElement>('button[aria-pressed="false"]')!.click();
    const all = p.messages.at(-1)!;
    expect(all).toMatchObject({ kind: 'preview-page', generation, window: { rowFilter: 'all', offset: 0, sort: { columnIndex: 0, direction: 'desc' } } });
    p.reply(all);
    p.state.page({ offset: 10 });
    p.reply(p.messages.at(-1)!);
    expect(p.state.window().offset).toBe(10);
    p.state.update({ ...options, dateOrder: 'DMY' });
    expect(p.messages.at(-1)).toMatchObject({ kind: 'preview-update', generation: generation + 1, window: { offset: 0, rowFilter: 'all', sort: { columnIndex: 0, direction: 'desc' } } });
    expect(p.messages.filter(m => m.kind === 'preview-init')).toHaveLength(1);
    p.state.destroy();
  });
  it('no acepta una ventana distinta con el id vigente ni una identidad de worker retirada', async () => {
    const p = await setup();
    p.state.page({ offset: 10 });
    const pending = p.messages.at(-1)!;
    if (!('window' in pending)) throw new Error('Falta ventana');
    p.reply(pending, { ...pending.window, columnIndices: [1] });
    expect(p.state.window().offset).toBe(0);
    expect(p.state.paging()).toBe(true);
    p.reply(pending);
    expect(p.state.window().offset).toBe(10);
    p.state.reset(undefined, {});
    p.reply(pending);
    expect(p.state.rows()).toEqual([]);
    expect(p.state.status()).toBe('idle');
    p.state.destroy();
  });
});
